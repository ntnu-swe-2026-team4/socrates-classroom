export type MessageKey = keyof (typeof messages)["zh-TW"];

export const dictionaries: Record<Locale, Record<MessageKey, string>> = messages;

const STORAGE_KEY = "locale";
let current: Locale = readInitial();
document.documentElement.lang = { "zh-TW": "zh-TW", en: "en", es: "es" }[current];

function readInitial(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    const normalized = saved === "zh" ? "zh-TW" : saved;
    if (normalized && (locales as readonly string[]).includes(normalized)) return normalized as Locale;
  } catch {}
  for (const tag of navigator.languages) {
    try {
      const base = new Intl.Locale(tag.toLowerCase()).language;
      const match = (locales as readonly string[]).find((l) => l.toLowerCase() === base);
      if (match) return match as Locale;
    } catch {}
  }
  return "zh-TW";
}

const listeners = new Set<() => void>();

export function setLocale(locale: Locale) {
  current = locale;
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {}
  document.documentElement.lang = { "zh-TW": "zh-TW", en: "en", es: "es" }[locale];
  for (const notify of listeners) notify();
}

export function subscribeLocale(notify: () => void) {
  listeners.add(notify);
  return () => listeners.delete(notify);
}

export function localeSnapshot(): Locale {
  return current;
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translate(locale: Locale, key: MessageKey, vars?: Record<string, string | number>): string {
  let text: string = dictionaries[locale][key] ?? messages["zh-TW"][key];
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  return text;
}

export function useI18n(): { t: Translate; locale: Locale } {
  const locale = useSyncExternalStore(subscribeLocale, localeSnapshot);
  const t = useCallback<Translate>((key, vars) => translate(locale, key, vars), [locale]);
  return { t, locale };
}

export function useT(): Translate {
  return useI18n().t;
}

export function useFormatDate(): (iso: string) => string {
  const { locale } = useI18n();
  return (iso) => new Date(iso).toLocaleDateString(locale);
}
